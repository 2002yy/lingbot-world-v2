#!/usr/bin/env python
"""§38B: Object Permanence audit.

For each object: look at it -> turn out of FOV (15 chunks) -> wait H chunks ->
turn back to the original pose. Compare the object's patch in frame 0 with the
return frame, in five dimensions:

    Existence   best DINO similarity in a search window above a threshold
    Identity    DINO similarity at the best match
    Pose        displacement of the best match (px)
    Attributes  LPIPS of the best-matched patch
    Relations   consistency of the pairwise offsets between objects

  LINGBOT_FP8=1 PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True \
  python object_permanence.py --scenes 04,01 --seeds 42
"""
